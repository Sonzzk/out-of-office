"""Blender layers -> game assets.
usage: python3 build_assets.py <layers dir> <repo dir>
Writes <repo>/public/office/*.png (640x360) and <repo>/src/data/office3d.ts
(screen positions from meta.json plus a 96-colour dither palette)."""
import sys, os, json, glob
import numpy as np
from PIL import Image
src, repo = sys.argv[1], sys.argv[2]
out = os.path.join(repo, 'public', 'office'); os.makedirs(out, exist_ok=True)
W, H = 640, 360
names = sorted(os.path.basename(p)[:-4] for p in glob.glob(os.path.join(src, '*.png')) if not p.endswith('closeup.png'))
imgs = {}
for n in names:
    im = Image.open(os.path.join(src, n + '.png')).convert('RGBA').resize((W, H), Image.LANCZOS)
    if n in ('base', 'dark'): im = im.convert('RGB')
    else:
        a = np.asarray(im).copy(); a[a[..., 3] < 6] = 0; im = Image.fromarray(a)
        bb = im.getbbox()
    imgs[n] = im
    im.save(os.path.join(out, n + '.png'), optimize=True)
# palette: the lit room with everything bought, the dark room, and extra weight on
# small saturated accents so median cut keeps them
full = imgs['base'].convert('RGBA')
for n in names:
    if n.startswith('up_') or n in ('fx_door_open', 'fx_figure'): full = Image.alpha_composite(full, imgs[n])
flat = np.concatenate([np.asarray(full.convert('RGB')).reshape(-1, 3), np.asarray(imgs['dark']).reshape(-1, 3)]).astype(float)
mx, mn = flat.max(1), flat.min(1); sat = (mx - mn) / (mx + 1)
acc = flat[sat > np.quantile(sat, 0.96)]; acc = acc[np.arange(len(flat) // 4) % len(acc)]
src_px = np.concatenate([flat, acc])
lum = (src_px * [0.3, 0.59, 0.11]).sum(1, keepdims=True); src_px = lum + (src_px - lum) * 1.2   # same boost as the game
src_px = src_px.clip(0, 255).astype('uint8')[None]
pal = Image.fromarray(src_px).quantize(96, method=Image.Quantize.MEDIANCUT).getpalette()[:64 * 3]
meta = json.load(open(os.path.join(src, 'meta.json')))
layers = [n for n in names if n not in ('base', 'dark')]
ts = f"""// Generated by backrooms-sim/3d-office/src/build_assets.py from the Blender
// render of the office (3d-office/src/office.py). Do not edit by hand.
// Positions are fractions of the 16:9 frame (x, y from the top left).

export const OFFICE_LAYERS = {json.dumps(layers)} as const;
export type OfficeLayer = (typeof OFFICE_LAYERS)[number];

/** The CRT screen's four corners. */
export const OFFICE_CRT: [number, number][] = {json.dumps(meta['crt'])};

/** Screen-space boxes [x0, y0, x1, y1] for clickable things and each layer. */
export const OFFICE_HOT: Record<string, [number, number, number, number]> = {json.dumps(meta['hot'], indent=1)};

/** 96 colours shared by every frame, so the dither matches the pixel art. */
export const OFFICE_PALETTE: number[] = {json.dumps(pal)};
"""
open(os.path.join(repo, 'src', 'data', 'office3d.ts'), 'w').write(ts)
print('wrote', len(names), 'images; total KB', sum(os.path.getsize(os.path.join(out, n + '.png')) for n in names) // 1024)
